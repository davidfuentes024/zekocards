/** Words whose every sound is inside `allowedIds`. Neutral marks are free. */
export function wordsWithin(allowedIds, { script = null } = {}) {
	if (!allowedIds || allowedIds.size === 0) return [];
	return WORDS.filter((w) => {
		if (script && w.script !== script) return false;
		return w.soundIds.every((id) => allowedIds.has(id));
	});
}

/** Words that use at least one of the given sounds (for card examples). */
export function wordsUsing(soundId, allowedIds = null) {
	return WORDS.filter(
		(w) =>
			w.soundIds.includes(soundId) &&
			(!allowedIds || w.soundIds.every((id) => allowedIds.has(id)))
	);
}
